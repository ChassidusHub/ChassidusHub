function variants(table: Record<string, string>, prefixes: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [he, en] of Object.entries(table)) {
    for (const [prefix, preposition] of Object.entries(prefixes)) {
      out[prefix + he] = preposition ? `${preposition} ${en}` : en;
    }
  }
  return out;
}

