/**
 * Each sicha's own name, ready to be searched: `name_he` and `name_en` are
 * its label as the search compares names (niqqud, gershayim and quotes
 * dropped, lower case, whatever is not a letter or a digit a space; the
 * same as normalizedSql in packages/core/src/searchText.ts), and `names`
 * holds their words, indexed.
 *
 * A search for `דברים ב` or `Devarim 2` should find that sicha by its
 * name. Its words cannot say so (they hold every word of it, and a common
 * one is in thousands), and comparing every one of the 69,000 labels on
 * each search took most of a second. The index finds the few whose name
 * holds the words; only those are compared whole.
 *
 * Generated by the database from `label`, so the trigger of migration
 * 0030 that keeps unit_place keeps these too, and adding them fills them
 * for every unit already there.
 */
const he = `btrim(regexp_replace(lower(regexp_replace(coalesce(label->>'he', ''), '[֑-ׇ׳״"''\`‘’“”]', '', 'g')), '[^0-9a-zÀ-ɏא-תװ-ײ]+', ' ', 'g'))`;
const en = `btrim(regexp_replace(lower(regexp_replace(coalesce(label->>'en', ''), '[֑-ׇ׳״"''\`‘’“”]', '', 'g')), '[^0-9a-zÀ-ɏא-תװ-ײ]+', ' ', 'g'))`;

export const up = /* sql */ `
ALTER TABLE unit_place
  ADD COLUMN name_he TEXT GENERATED ALWAYS AS (${he}) STORED,
  ADD COLUMN name_en TEXT GENERATED ALWAYS AS (${en}) STORED,
  ADD COLUMN names TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple'::regconfig, ${he} || ' ' || ${en})) STORED;
CREATE INDEX unit_place_names ON unit_place USING gin (names);
`;
