#!/usr/bin/env node
/**
 * Writes the works the phone bundles (catalog schema 3):
 *
 *   <out>/works.json              every author and work, without units
 *   <out>/contents/<work>.json    an imported work's contents and units, one file per work
 *   <out>/shelf.json              the HebrewBooks shelf, by author and series
 *   <out>/index.ts                the loaders the phone imports (each part read on first use)
 *
 * The index is `works.json`, never `index.json`: Metro resolves the folder
 * to `index.json` before `index.ts`, and the phone would import the data in
 * place of its loaders.
 *
 *   --imports <dir>   an importer's output, one folder per work with a work.json
 *                     (default: packages/sefaria-index/data); may be given more than once
 *   --shelf <file>    the HebrewBooks shelf (default: packages/hebrewbooks-index/data/shelf.json,
 *                     from `import-hebrewbooks`); --without-shelf builds without it
 *   --out <dir>       default: apps/mobile/src/catalog/data/works
 *
 * Run `sefaria-index import`, `import-igros` and `import-hebrewbooks` first.
 * Their output is gitignored; this command's output is committed, like the
 * library build's.
 */
import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCatalogWorks, worksRightsProblems } from '@sichos-kodesh/catalog';
import type { HebrewBooksShelf } from '@sichos-kodesh/hebrewbooks-index';
import { buildCatalogWorks } from '../src/catalogWorks.js';
import { placeShelf } from '../src/shelf.js';
import { WORKS } from '../src/registry/works.js';
import type { ImportedWork } from '../src/types.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, '..', '..', '..');

function args(name: string): string[] {
  const found: string[] = [];
  process.argv.forEach((value, i) => {
    if (value === `--${name}` && process.argv[i + 1]) found.push(process.argv[i + 1]!);
  });
  return found;
}

const importDirs = args('imports');
if (importDirs.length === 0) importDirs.push(path.join(repoRoot, 'packages', 'sefaria-index', 'data'));
const outDir = args('out')[0] ?? path.join(repoRoot, 'apps', 'mobile', 'src', 'catalog', 'data', 'works');

const imports: ImportedWork[] = [];
for (const dir of importDirs) {
  if (!existsSync(dir)) {
    console.error(`${dir} does not exist: run the importer first (npm run sefaria-index -w @sichos-kodesh/sefaria-index -- import)`);
    process.exit(1);
  }
  for (const name of (await readdir(dir)).sort()) {
    const file = path.join(dir, name, 'work.json');
    if (!name.startsWith('.') && existsSync(file)) imports.push(JSON.parse(await readFile(file, 'utf8')) as ImportedWork);
  }
}

let hebrewBooks: HebrewBooksShelf | undefined;
if (!process.argv.includes('--without-shelf')) {
  const shelfFile = args('shelf')[0] ?? path.join(repoRoot, 'packages', 'hebrewbooks-index', 'data', 'shelf.json');
  if (!existsSync(shelfFile)) {
    console.error(`${shelfFile} does not exist: run import-hebrewbooks first (npm run import-hebrewbooks -w @sichos-kodesh/hebrewbooks-index -- --catalog <otzar-HB_catalog.db.zst>), or pass --without-shelf`);
    process.exit(1);
  }
  hebrewBooks = JSON.parse(await readFile(shelfFile, 'utf8')) as HebrewBooksShelf;
  const { unmatched } = placeShelf(hebrewBooks, WORKS);
  if (unmatched.length > 0) console.warn(`Names in registry/hebrewbooks.ts that match no series on the shelf:\n  ${unmatched.join('\n  ')}`);
}

const works = buildCatalogWorks(imports, hebrewBooks);
if (!parseCatalogWorks(works)) {
  console.error('The built works do not validate (parseCatalogWorks).');
  process.exit(1);
}
const problems = worksRightsProblems(works);
if (problems.length > 0) {
  console.error(`The built works carry text that may not ship:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

await rm(outDir, { recursive: true, force: true });
await mkdir(path.join(outDir, 'contents'), { recursive: true });
await writeFile(path.join(outDir, 'works.json'), JSON.stringify({ authors: works.authors, works: works.works }), 'utf8');
const ids = Object.keys(works.contents);
for (const id of ids) await writeFile(path.join(outDir, 'contents', `${id}.json`), JSON.stringify(works.contents[id]), 'utf8');
if (works.shelf) await writeFile(path.join(outDir, 'shelf.json'), JSON.stringify(works.shelf), 'utf8');

// Metro bundles every file a string-literal `require` names; a `require`
// inside a function parses its JSON only when called, so a work's units
// cost nothing until that work is opened.
const lines = [
  '// Generated by packages/works/bin/build-catalog-works.ts - do not edit by hand.',
  `import type { CatalogWorkContents, CatalogWorksIndex${works.shelf ? ', CatalogShelf' : ''} } from '@sichos-kodesh/catalog';`,
  '',
  'declare const require: (path: string) => unknown;',
  '',
  'let index: CatalogWorksIndex | null = null;',
  '',
  '/** Every author and work bundled with this build, read on first use. */',
  'export default function bundledWorks(): CatalogWorksIndex {',
  "  index ??= require('./works.json') as CatalogWorksIndex;",
  '  return index;',
  '}',
  '',
  'const CONTENTS: Record<string, () => CatalogWorkContents> = {',
  ...ids.map((id) => `  ${JSON.stringify(id)}: () => require('./contents/${id}.json') as CatalogWorkContents,`),
  '};',
  '',
  '/** An imported work\'s contents and units, read when the work is opened; null for a work without its own. */',
  'export function bundledWorkContents(workId: string): CatalogWorkContents | null {',
  '  const load = CONTENTS[workId];',
  '  return load ? load() : null;',
  '}',
  '',
  ...(works.shelf
    ? [
        'let shelf: CatalogShelf | null = null;',
        '',
        '/** The HebrewBooks shelf, read when a screen first needs it. */',
        'export function bundledShelf(): CatalogShelf | null {',
        "  shelf ??= require('./shelf.json') as CatalogShelf;",
        '  return shelf;',
        '}',
        '',
      ]
    : ['/** This build has no HebrewBooks shelf. */', 'export function bundledShelf(): null {', '  return null;', '}', '']),
];
await writeFile(path.join(outDir, 'index.ts'), lines.join('\n'), 'utf8');

const units = ids.reduce((sum, id) => sum + works.contents[id]!.units.length, 0);
const scans = works.shelf?.authors.reduce((n, a) => n + a.series.reduce((m, s) => m + s.scans.length, 0), 0) ?? 0;
const placedScans = works.shelf?.authors.reduce((n, a) => n + a.series.filter((s) => s.workId).reduce((m, s) => m + s.scans.length, 0), 0) ?? 0;
console.log(`Wrote ${outDir}: ${works.authors.length} authors, ${works.works.length} works; ${ids.length} with their own units (${units} units)`);
if (works.shelf) console.log(`HebrewBooks shelf (Otzaria catalog ${works.shelf.catalogVersion}): ${scans} scans, ${placedScans} of them placed with a sefer`);
