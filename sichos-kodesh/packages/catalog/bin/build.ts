#!/usr/bin/env node
import { DatabaseSync } from 'node:sqlite';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { existsSync } from 'node:fs';
import { MIN_HISTORICAL_YEAR } from '@sichos-kodesh/kvius-engine';
import { buildCatalog } from '../src/buildCatalog.js';
import { buildLibrary } from '../src/library/buildLibrary.js';
import { translateLibrary } from '../src/translate/library.js';
import { shortenCatalogYear, shortenLibrary } from '../src/translate/shortTitles.js';
import { loadLibraryEditions, loadLibraryTranslations, loadShortTitles } from './libraryTranslations.js';
import { addLibraryViews } from '../src/library/views.js';
import { buildGatedLibrary } from '../src/library/gated.js';
import { LIBRARY_COLLECTION_IDS } from '../src/library/types.js';

/**
 * Writes the catalog the apps bundle:
 *
 *   <out>/<year>.json + index.ts   the farbrengens (schema 1) - copied into both apps
 *   <out>/library/                 the library (schema 2) - copied into apps/mobile only
 *
 *   --db <path>        mafteiach.db (default: packages/mafteiach-index/mafteiach.db)
 *   --jem-db <path>    jem.db for the jemEvents collection (default: packages/jem-index/jem.db, skipped when absent)
 *   --without-jem      build the library without the jemEvents collection
 *   --igros <dir>      also build the Igros and Maanos as library collections from packages/igros-index's
 *                      output, into <out>/library-gated/ - for local use only, never copied into an
 *                      app, and refused when --out is inside apps/ (the Maanos are gated, src/rights.ts;
 *                      the Igros reach the apps as a sefer instead: igros-index's import-igros)
 *   --out <dir>        default: packages/catalog/data
 */

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function arg(name: string, fallback: string): string {
  const idx = process.argv.indexOf(`--${name}`);
  return idx !== -1 && process.argv[idx + 1] ? process.argv[idx + 1]! : fallback;
}

const dbPath = arg('db', path.join(__dirname, '..', '..', 'mafteiach-index', 'mafteiach.db'));
const jemDbPath = arg('jem-db', path.join(__dirname, '..', '..', 'jem-index', 'jem.db'));
const withJem = !process.argv.includes('--without-jem') && existsSync(jemDbPath);
const outDir = arg('out', path.join(__dirname, '..', 'data'));
// The Maanos are gated (src/rights.ts), and these collections go into no
// app: refused up front when the output is inside apps/, before anything is written.
const igrosDir = arg('igros', '');
if (igrosDir) {
  const appsDir = path.resolve(__dirname, '..', '..', '..', 'apps');
  const resolvedOut = path.resolve(outDir);
  if (resolvedOut === appsDir || resolvedOut.startsWith(appsDir + path.sep)) {
    console.error(`--igros: ${resolvedOut} is inside apps/. These collections never go into an app (the Maanos are gated, src/rights.ts); pass another --out.`);
    process.exit(1);
  }
}

const db = new DatabaseSync(dbPath, { readOnly: true });
const byYear = buildCatalog(db);
// Same floor as browsableYears/findMatchingYears: this app is scoped to the
// current Rebbe's own Sichos Kodesh (5710 onward), not the Previous Rebbe's
// pre-Nesius farbrengens - no bundled app ever looks up an earlier year, so
// there's no reason to ship those year files at all.
const years = Object.keys(byYear)
  .filter((year) => Number(year) >= MIN_HISTORICAL_YEAR)
  .sort((a, b) => Number(a) - Number(b));

await mkdir(outDir, { recursive: true });
// Each long name with its short title beside it (src/translate/shortTitles.ts).
const shortTitles = await loadShortTitles();
let totalEntries = 0;
for (const year of years) {
  await writeFile(path.join(outDir, `${year}.json`), JSON.stringify(shortenCatalogYear(byYear[Number(year)]!, shortTitles), null, 2), 'utf8');
  totalEntries += byYear[Number(year)]!.length;
}

// Metro (React Native's bundler) only bundles statically-analyzable imports, not a
// runtime-computed list of filenames - so this barrel file is what a consumer like
// apps/mobile actually imports, not the raw JSON files directly.
const indexLines = [
  '// Generated by packages/catalog/bin/build.ts - do not edit by hand.',
  "import type { CatalogByYear } from '@sichos-kodesh/catalog';",
  ...years.map((year) => `import year${year} from './${year}.json';`),
  '',
  `const catalog: CatalogByYear = {`,
  ...years.map((year) => `  ${year}: year${year} as CatalogByYear[number],`),
  '};',
  '',
  'export default catalog;',
  '',
];
await writeFile(path.join(outDir, 'index.ts'), indexLines.join('\n'), 'utf8');

console.log(`Wrote ${years.length} year files + index.ts (${totalEntries} occasions) to ${outDir}`);

// The library (schema 2), one file per collection plus the moadim and
// parshiyos. Compact JSON: these files are bundled only by the phone app and
// read by bin/release.ts, never diffed by hand.
const jemDb = withJem ? new DatabaseSync(jemDbPath, { readOnly: true }) : null;
// With each name in the other language beside it (src/translate/library.ts).
const library = addLibraryViews(shortenLibrary(translateLibrary(buildLibrary(db, jemDb), await loadLibraryTranslations()), shortTitles), await loadLibraryEditions());
const libraryDir = path.join(outDir, 'library');
await mkdir(libraryDir, { recursive: true });
await writeFile(path.join(libraryDir, 'meta.json'), JSON.stringify({ moadim: library.moadim, parshiyos: library.parshiyos }), 'utf8');
for (const id of LIBRARY_COLLECTION_IDS) {
  await writeFile(path.join(libraryDir, `${id}.json`), JSON.stringify(library.collections[id]), 'utf8');
}

// Metro bundles every file a string-literal `require` names, but a `require`
// inside a function only runs - and parses the JSON - when it is called, so
// the library costs nothing at start-up until a library screen asks for it.
const libraryIndexLines = [
  '// Generated by packages/catalog/bin/build.ts - do not edit by hand.',
  "import type { CatalogLibrary, LibraryCollections, OccasionGroup } from '@sichos-kodesh/catalog';",
  '',
  'declare const require: (path: string) => unknown;',
  '',
  'let library: CatalogLibrary | null = null;',
  '',
  '/** The library bundled with this build, read on first use. */',
  'export default function bundledLibrary(): CatalogLibrary {',
  '  if (!library) {',
  "    const meta = require('./meta.json') as { moadim: OccasionGroup[]; parshiyos: OccasionGroup[] };",
  '    library = {',
  '      moadim: meta.moadim,',
  '      parshiyos: meta.parshiyos,',
  '      collections: {',
  ...LIBRARY_COLLECTION_IDS.map((id) => `        ${id}: require('./${id}.json') as LibraryCollections['${id}'],`),
  '      },',
  '    };',
  '  }',
  '  return library;',
  '}',
  '',
];
await writeFile(path.join(libraryDir, 'index.ts'), libraryIndexLines.join('\n'), 'utf8');
const counts = LIBRARY_COLLECTION_IDS.map((id) => `${id} ${library.collections[id].items.length}`).join(', ');
console.log(`Wrote the library to ${libraryDir}: ${library.moadim.length} moadim, ${library.parshiyos.length} parshiyos; ${counts}${withJem ? '' : ' (without jem.db)'}`);

// The gated collections get their own folder, so copying library/ into the
// phone can never take them along.
if (igrosDir) {
  const { readIgrosOutput } = await import('@sichos-kodesh/igros-index');
  const { letters, maanos } = readIgrosOutput(igrosDir);
  const gated = buildGatedLibrary(letters, maanos);
  const gatedDir = path.join(outDir, 'library-gated');
  await mkdir(gatedDir, { recursive: true });
  await writeFile(path.join(gatedDir, 'igros.json'), JSON.stringify(gated.igros), 'utf8');
  await writeFile(path.join(gatedDir, 'maanos.json'), JSON.stringify(gated.maanos), 'utf8');
  console.log(`Wrote the gated collections to ${gatedDir}: igros ${gated.igros.items.length} in ${gated.igros.groups.volume!.length} volumes, maanos ${gated.maanos.items.length} in ${gated.maanos.groups.year!.length} years - local only`);
}
