#!/usr/bin/env node
import { DatabaseSync } from 'node:sqlite';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCatalog } from '../src/buildCatalog.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function arg(name: string, fallback: string): string {
  const idx = process.argv.indexOf(`--${name}`);
  return idx !== -1 && process.argv[idx + 1] ? process.argv[idx + 1]! : fallback;
}

const dbPath = arg('db', path.join(__dirname, '..', '..', 'mafteiach-index', 'mafteiach.db'));
const outDir = arg('out', path.join(__dirname, '..', 'data'));

const db = new DatabaseSync(dbPath, { readOnly: true });
const byYear = buildCatalog(db);
const years = Object.keys(byYear).sort((a, b) => Number(a) - Number(b));

await mkdir(outDir, { recursive: true });
let totalEntries = 0;
for (const year of years) {
  await writeFile(path.join(outDir, `${year}.json`), JSON.stringify(byYear[Number(year)], null, 2), 'utf8');
  totalEntries += byYear[Number(year)]!.length;
}

// Metro (React Native's bundler) only bundles statically-analyzable imports, not a
// runtime-computed list of filenames - so this barrel file is what a consumer like
// apps/mobile actually imports, not the raw JSON files directly.
const indexLines = [
  '// Generated by packages/catalog/bin/build.ts - do not edit by hand.',
  "import type { CatalogByYear } from '@sichos-kodesh/catalog';",
  ...years.map((year) => `import year${year} from './${year}.json';`),
  '',
  `const catalog: CatalogByYear = {`,
  ...years.map((year) => `  ${year}: year${year} as CatalogByYear[number],`),
  '};',
  '',
  'export default catalog;',
  '',
];
await writeFile(path.join(outDir, 'index.ts'), indexLines.join('\n'), 'utf8');

console.log(`Wrote ${years.length} year files + index.ts (${totalEntries} occasions) to ${outDir}`);
