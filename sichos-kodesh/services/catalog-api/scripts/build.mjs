#!/usr/bin/env node
/**
 * Turns this repository's catalog into the two files the API serves and
 * bakes them into one generated module the Vercel function imports:
 *
 *   1. `npm run release-files -w @sichos-kodesh/catalog` writes
 *      catalog.json + manifest.json (packages/catalog/bin/release.ts) from
 *      the year files the apps bundle, stamped with CATALOG_VERSION and the
 *      deployed commit's own date - so the same commit always produces the
 *      same manifest.
 *   2. generated/release.ts exports both files as string constants. The
 *      function serves the catalog string's exact UTF-8 bytes, which is
 *      what the manifest's sha256 was computed over.
 *
 * Runs as the Vercel build command (root directory services/catalog-api)
 * and before the tests. A release is therefore "what is on the deployed
 * commit": bumping CATALOG_VERSION on main and letting Vercel deploy it is
 * what publishes a new catalog; the catalog-v<version> tag is the archive
 * of that same data on GitHub.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const serviceRoot = path.join(here, '..');
const repoRoot = path.join(serviceRoot, '..', '..');
const releaseDir = path.join(serviceRoot, 'generated', 'release-files');
const generatedModule = path.join(serviceRoot, 'generated', 'release.ts');

function commitDate() {
  try {
    return execFileSync('git', ['log', '-1', '--format=%cI'], { cwd: repoRoot, encoding: 'utf8' }).trim();
  } catch {
    return ''; // No git metadata (a tarball build) - release.ts stamps "now".
  }
}

await mkdir(releaseDir, { recursive: true });
const args = ['run', 'release-files', '-w', '@sichos-kodesh/catalog', '--', '--out', releaseDir];
const releasedAt = commitDate();
if (releasedAt) args.push('--released-at', releasedAt);
execFileSync('npm', args, { cwd: repoRoot, stdio: 'inherit' });

const read = (name) => readFile(path.join(releaseDir, name), 'utf8');
const sha256 = (text) => createHash('sha256').update(Buffer.from(text, 'utf8')).digest('hex');

// Both schemas' catalog.json share the farbrengens (`byYear`) byte for byte,
// so the bundle keeps one copy of it and each file's short head, and the
// router puts each file back together. Checked here against the manifests'
// sha256, so a mismatch fails the build instead of serving a wrong file.
const byYearJson = await read('parts/byYear.json');
const manifestJson = await read('manifest.json');
const manifest = JSON.parse(manifestJson);
const catalogJson = await read('catalog.json');
const catalogTail = `${byYearJson}}`;
if (!catalogJson.endsWith(catalogTail)) throw new Error('catalog.json does not end with parts/byYear.json');
const catalogHead = catalogJson.slice(0, catalogJson.length - catalogTail.length);
if (sha256(catalogHead + catalogTail) !== manifest.sha256) throw new Error('catalog.json does not reassemble to its manifest sha256');

let libraryManifestJson = '';
let libraryJson = '';
let libraryHead = '';
if (existsSync(path.join(releaseDir, 'v2', 'manifest.json'))) {
  libraryManifestJson = await read('v2/manifest.json');
  libraryJson = await read('parts/library.json');
  const libraryManifest = JSON.parse(libraryManifestJson);
  const v2Json = await read('v2/catalog.json');
  const v2Tail = `${byYearJson},"library":${libraryJson}}`;
  if (!v2Json.endsWith(v2Tail)) throw new Error('v2/catalog.json does not end with the farbrengens and the library');
  libraryHead = v2Json.slice(0, v2Json.length - v2Tail.length);
  if (sha256(libraryHead + v2Tail) !== libraryManifest.sha256) throw new Error('v2/catalog.json does not reassemble to its manifest sha256');
}

const lines = [
  '// Generated by scripts/build.mjs - do not edit, do not commit (see .gitignore).',
  `// Catalog ${manifest.version}, ${manifest.occasions} occasions across ${manifest.years.length} years, released ${manifest.releasedAt}${libraryJson ? ', with the library (schema 2)' : ''}.`,
  '',
  '/** manifest.json (schema 1) as written by packages/catalog/bin/release.ts; the function rewrites its `url` to the request\'s own origin. */',
  `export const manifestJson: string = ${JSON.stringify(manifestJson)};`,
  '',
  '/** The farbrengens, as they sit inside both catalog.json files. */',
  `export const byYearJson: string = ${JSON.stringify(byYearJson)};`,
  '',
  '/** Schema 1 catalog.json = catalogHead + byYearJson + "}" - byte for byte what its manifest describes. */',
  `export const catalogHead: string = ${JSON.stringify(catalogHead)};`,
  '',
  '/** Schema 2 (the phone\'s library): its manifest, the library\'s JSON, and the head of v2/catalog.json; empty when the release has no library. */',
  `export const libraryManifestJson: string = ${JSON.stringify(libraryManifestJson)};`,
  `export const libraryJson: string = ${JSON.stringify(libraryJson)};`,
  `export const libraryHead: string = ${JSON.stringify(libraryHead)};`,
  '',
];
await writeFile(generatedModule, lines.join('\n'), 'utf8');
console.log(
  `catalog-api: generated release.ts for catalog ${manifest.version} (${(manifest.bytes / 1024 / 1024).toFixed(2)} MB${libraryJson ? `; with the library, ${(JSON.parse(libraryManifestJson).bytes / 1024 / 1024).toFixed(2)} MB` : ''})`,
);

// Bundle the Vercel function. The entry is TypeScript importing
// src/router.ts, which Vercel's builder does not compile, so a bare build
// used to deploy a function that crashed on boot (ERR_MODULE_NOT_FOUND
// for ../src/router -> 500 on every request). Bundling here produces the
// single self-contained api/index.js that Vercel deploys. The bundle is
// COMMITTED (not gitignored): Vercel only discovers function entrypoints
// that exist in the source tree, so a build-time-only api/index.js is
// never picked up. The source lives in src/handler.ts; the
// catalog-api-bundle workflow rebuilds and commits the bundle on every
// push to main touching this service.
execFileSync('npx', ['esbuild', 'src/handler.ts', '--bundle', '--platform=node', '--target=node24', '--format=esm', '--outfile=api/index.js', '--log-level=warning'], { cwd: serviceRoot, stdio: 'inherit' });
console.log('catalog-api: bundled src/handler.ts -> api/index.js');
